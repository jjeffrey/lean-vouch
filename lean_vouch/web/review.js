// Review controls for doc-gen4 pages. Each declaration gets a mark (✓ / ? / ✗) and a thread of
// notes, saved through server.py. With a declaration graph, a mark is flagged when the
// declaration or anything it depends on has changed since it was made, project declarations list
// the library definitions they use, and those library definitions can be marked as understood.
(() => {
  const PROJECT_STATUS = [
    ["agree", "✓", "I agree with this"],
    ["question", "?", "I have a question"],
    ["reject", "✗", "I reject how this is defined"],
  ];
  const SYMBOL = { agree: "✓", question: "?", reject: "✗" };
  const LIBRARY_STATUS = [
    ["agree", "✓", "I understand this"],
    ["question", "?", "I have a question about this"],
    ["reject", "✗", "This surprises me or seems wrong"],
  ];
  // Generated by `deriving`; nothing to review.
  // The graph knows for the project's own; a library's only has a name to go by.
  const isGenerated = name => name in graph.declarations ? !!graph.declarations[name].derived
    : /\.inst(Repr|DecidableEq|BEq|Hashable|Inhabited|Nonempty)/.test(name);
  const short = name => name.replace(/^[^.]*\./, "");

  let marks = {}, graph = { declarations: {}, library: {}, renames: {} };
  const info = name => name.startsWith("module ")
    ? { module: name.slice(7), own: graph.moduleDocs?.[name.slice(7)] } : graph.declarations[name] ?? graph.library[name];

  // Groups of Core Lean plumbing (tagged by DeclGraph.lean), hidden unless switched on. The
  // choice is remembered in this browser. Hidden library uses are neither listed nor counted as
  // changes.
  const GROUPS = [
    ["compiler", "compiler plumbing", "what Lean compiles recursion, matching and deriving into"],
    ["notation", "if / do / try", "what if, match, do, throw and try mean"],
    ["internals", "internals", "formatting and string-slice internals"],
    ["theorems", "library theorems", "library theorems used inside definitions"],
  ];
  const storageKey = "lean-vouch.shownGroups";
  let shownGroups = new Set();
  try { shownGroups = new Set(JSON.parse(localStorage.getItem(storageKey) ?? "[]")); } catch {}
  const visible = name => {
    const l = graph.library[name];
    return !l || graph.declarations[name] || !l.group || shownGroups.has(l.group);
  };
  // doc-gen4 folds each definition's equations; for review they are what's being checked, so
  // project declarations show them open unless switched off (remembered in this browser, shared
  // with the diagram's sidebar). Library pages keep doc-gen4's folding.
  const equationsKey = "lean-vouch.openEquations";
  let openEquations = true;
  try { openEquations = localStorage.getItem(equationsKey) !== "0"; } catch {}
  const equations = decl => [...decl.querySelectorAll("details")]
    .filter(d => d.querySelector(":scope > summary")?.textContent.trim() === "Equations");
  const docLink = name => {
    const i = info(name);
    return i ? `${SITE_ROOT}${i.module.replaceAll(".", "/")}.html#${name}` : null;
  };

  // Everything a project declaration depends on: project declarations below it and the library
  // definitions they use.
  const closureCache = new Map();
  function closure(name) {
    if (closureCache.has(name)) return closureCache.get(name);
    const out = new Set(), stack = [name];
    while (stack.length) {
      const d = graph.declarations[stack.pop()];
      if (d) for (const dep of [...d.deps, ...d.uses]) if (!out.has(dep)) { out.add(dep); stack.push(dep); }
    }
    closureCache.set(name, out);
    return out;
  }
  // What changed since a mark was made: the declaration itself, and/or things it depends on.
  // Library uses in hidden groups don't count.
  function changes(name, mark) {
    const fp = mark.fingerprint;
    if (fp && info(name)) {
      const self = fp.own !== info(name).own;
      const now = closure(name);
      const deps = [...new Set([...Object.keys(fp.deps), ...now])].filter(d => visible(d) &&
        (fp.deps[d] ?? null) !== (info(d)?.own ?? null));
      return { self, deps };
    }
    return { self: false, deps: [] };
  }

  // One note in a thread: the author and date on a line of their own, then the text. Yours, other
  // people's and the tool's are styled differently, like a conversation.
  const noteItem = n => {
    const li = document.createElement("li");
    li.className = n.by === "lean-vouch" ? "by-tool" : n.mine ? "by-reviewer" : "by-other";
    li.style.setProperty("--person-hue", reviewHue(n.by));
    const head = document.createElement("div");
    head.className = "note-head";
    head.textContent = n.by + (n.quiz ? " · quiz answer " : " ");
    const date = document.createElement("span");
    date.className = "note-date";
    date.textContent = n.date.slice(0, 10);
    head.append(date);
    const text = document.createElement("div");
    text.textContent = n.text;
    li.append(head, text);
    return li;
  };
  const checked = reviewChecked, post = reviewPost;
  const el = (tag, cls, text) => {
    const e = document.createElement(tag);
    if (cls) e.className = cls;
    if (text !== undefined) e.textContent = text;
    return e;
  };
  const link = (name, label) => {
    const a = el("a", "review-ref", label ?? short(name));
    const href = docLink(name);
    if (href) a.href = href;
    const s = marks[name]?.status;
    if (s) a.dataset.status = s;
    return a;
  };

  const renderers = new Map();   // how to redraw each declaration on this page
  // A change to one mark can change what others show, since they count what relies on what.
  const redraw = () => {
    for (const [name, render] of renderers) render(marks[name] ?? {});
    showBar();
  };
  let showBar = () => {};

  // What changed, and how many of your marks rely on each. Every mark recorded what lay below it,
  // so this includes declarations you never marked.
  let changedNow = null;
  const changedNames = () => {
    if (changedNow) return changedNow;
    const found = changedNow = new Map();
    for (const [name, mark] of Object.entries(marks)) {
      if (!mark.status || !mark.fingerprint) continue;
      const c = changes(name, mark);
      for (const d of [...(c.self ? [name] : []), ...c.deps]) found.set(d, (found.get(d) ?? 0) + 1);
    }
    return found;
  };

  function controls(name, element, library) {
    const box = el("div", "review");
    if (isGenerated(name)) {
      element.classList.add("review-generated");
      for (const a of document.querySelectorAll(`.internal_nav .nav_link a[href="#${CSS.escape(name)}"]`))
        a.closest(".nav_link").classList.add("review-generated");
    }
    if (library) {
      const users = Object.entries(graph.declarations).filter(([, d]) => d.uses.includes(name)).map(([n]) => n);
      const line = el("div", "review-uses", "Used by the project in: ");
      users.forEach((u, i) => { if (i) line.append(", "); line.append(link(u)); });
      box.append(line);
    } else {
      const uses = (graph.declarations[name]?.uses ?? []).filter(visible);
      if (uses.length) {
        const line = el("div", "review-uses", "Uses from libraries: ");
        uses.forEach((u, i) => { if (i) line.append(", "); line.append(link(u, u)); });
        box.append(line);
      }
    }
    // What the proof rests on, besides Lean's three standard axioms. A `sorry` counts here whether or
    // not the statement is agreed: a mark is about the statement, this is about the proof.
    const decl = library ? null : graph.declarations[name];
    if (decl?.sorry || decl?.sorryFrom?.length) {
      const line = el("div", decl.sorry ? "review-gap source" : "review-gap");
      if (decl.sorry) line.append("Contains sorry.");
      if (decl.sorryFrom?.length) {
        line.append(decl.sorry ? " Also relies on sorry in " : "Proved only if these are: ");
        decl.sorryFrom.forEach((s, i) => { if (i) line.append(", "); line.append(link(s, short(s))); });
        const steps = (decl.sorryVia ?? []).filter(v => !decl.sorryFrom.includes(v));
        if (steps.length) {
          line.append(", by way of ");
          steps.forEach((s, i) => { if (i) line.append(", "); line.append(link(s, short(s))); });
        }
      }
      box.append(line);
      element.dataset.reviewGap = decl.sorry ? "source" : "affected";
    }
    if (decl?.axioms?.length) box.append(el("div", "review-axioms", `Also trusts: ${decl.axioms.join(", ")}`));
    const row = el("div", "review-row");
    const buttons = (library ? LIBRARY_STATUS : PROJECT_STATUS).map(([status, label, title]) => {
      const b = el("button", null, label);
      b.title = title;
      b.dataset.status = status;
      row.append(b);
      return b;
    });
    const stale = el("span", "review-stale");
    row.append(stale);
    const others = el("div", "review-others");
    box.append(row, others);
    const notes = el("ul", "review-notes");
    const input = el("textarea");
    input.placeholder = "Add a note…";
    input.rows = 2;
    const add = el("button", "review-add", "Add note");
    box.append(notes, input, add);
    const prompt = el("div", "review-prompt", "What's your question? Others see it once you write one.");
    notes.after(prompt);
    const unexplained = e => e.status === "question" && !(e.notes ?? []).some(n => n.mine && n.by !== "lean-vouch");

    const render = e => {
      if (e !== marks[name] && (e.status || marks[name]?.status)) changedNow = null;
      marks[name] = e;
      prompt.hidden = !unexplained(e);
      for (const b of buttons) b.classList.toggle("active", e.status === b.dataset.status);
      element.dataset.reviewStatus = e.status ?? "";
      const c = e.status ? changes(name, e) : { self: false, deps: [] };
      stale.replaceChildren();
      const relying = changedNames().get(name);
      if (c.self) stale.append("changed since you marked it");
      else if (relying) stale.append(`changed since ${relying} of your marks relied on it`);
      else if (c.deps.length) {
        stale.append("depends on ");
        c.deps.forEach((d, i) => { if (i) stale.append(", "); stale.append(link(d, short(d))); });
        stale.append(", which changed since you marked it");
      }
      if (c.self || c.deps.length) {
        // Keeps the mark, for what's there now. Clicking it again would clear it.
        const accept = el("button", "review-accept", "Accept change");
        accept.title = "Keep your mark for the current version. Only this declaration's mark is affected.";
        accept.onclick = async () => { await post("/review/data", { name, status: e.status }).then(render); redraw(); };
        stale.append(" ", accept);
      }
      element.dataset.reviewStale = c.self || c.deps.length ? "yes" : "";
      element.dataset.reviewChange = c.self || relying ? "changed" : c.deps.length ? "affected" : "";
      // Only marks of what's there now can disagree.
      const isCurrent = m => { const d = changes(name, m); return !d.self && !d.deps.length; };
      const current = [...(e.status && isCurrent(e) ? [e.status] : []),
        ...(e.others ?? []).filter(isCurrent).map(o => o.status)];
      const disagree = new Set(current).size > 1;
      element.dataset.reviewDisagree = disagree ? "yes" : "";
      element.dataset.reviewAttention = e.attention?.length ? "yes" : "";
      others.replaceChildren(...(e.others ?? []).map(o =>
        el("span", isCurrent(o) ? null : "old", `${o.name}: ${SYMBOL[o.status]}${isCurrent(o) ? "" : " (changed since)"}`)));
      const differing = reviewDisagreement(e.status && isCurrent(e) ? e.status : null, (e.others ?? []).filter(isCurrent));
      if (differing) others.append(el("span", "disagree", differing));
      if (e.attention?.length) others.append(el("span", "attention", `needs your attention: ${e.attention.join(", ")}`));
      notes.replaceChildren(...(e.notes ?? []).map(noteItem));
      summarize();
    };
    for (const b of buttons)
      b.onclick = async () => {
        const status = b.classList.contains("active") ? null : b.dataset.status;
        render(await post("/review/data", { name, status }));
        if (unexplained(marks[name])) input.focus();
      };
    add.onclick = async () => {
      const note = input.value.trim();
      if (!note) return;
      render(await post("/review/data", { name, note }));
      input.value = "";
    };
    element.append(box);
    renderers.set(name, render);
    render(marks[name] ?? {});
  }

  // Marks whose declaration isn't in the last build, e.g. after a refactor.
  function orphans() {
    const modules = new Set(graph.moduleNames ?? Object.keys(graph.modules ?? {}));
    return Object.keys(marks).filter(k => (marks[k].status || marks[k].notes?.some(n => n.mine)) &&
      (k.startsWith("module ") ? !modules.has(k.slice(7)) : !info(k)));
  }

  function orphanPanel() {
    const panel = el("div", "review-orphans");
    const close = el("button", "review-close", "close");
    close.onclick = () => panel.remove();
    panel.append(el("h3", null, "Orphaned notes"), close,
      el("p", null, "These marks aren't in the last build: their declarations were removed or renamed, or a library was left out of it. Move each to the declaration it now belongs to, or delete it."));
    for (const name of orphans()) {
      const item = el("div", "review-orphan");
      item.append(el("strong", null, name));
      const notes = el("ul", "review-notes");
      for (const n of marks[name].notes ?? []) notes.append(noteItem(n));
      const to = el("input");
      to.placeholder = "move to (full name)";
      to.setAttribute("list", "review-names");
      const move = el("button", null, "Move");
      move.onclick = async () => {
        const r = await post("/review/move", { from: name, to: to.value.trim() });
        if (r.error) return alert(r.error);
        reviewReload();
      };
      const del = el("button", null, "Delete");
      del.onclick = async () => {
        if (!confirm(`Delete the mark and notes for ${name}?`)) return;
        await post("/review/delete", { name });
        reviewReload();
      };
      item.append(notes, to, move, del);
      panel.append(item);
    }
    const names = el("datalist");
    names.id = "review-names";
    for (const n of Object.keys(graph.declarations)) names.append(Object.assign(el("option"), { value: n }));
    panel.append(names);
    document.body.append(panel);
  }

  // The lowest first: what a change means depends on what's beneath it.
  function changedPanel() {
    const panel = el("div", "review-orphans");
    const close = el("button", "review-close", "close");
    close.onclick = () => panel.remove();
    panel.append(el("h3", null, "What changed"), close,
      el("p", null, "Each of these changed since marks that rely on it were made. Start at the top: what a change means depends on what's beneath it."));
    const list = el("ul"), found = changedNames();
    for (const name of [...found.keys()].sort((a, b) => closure(a).size - closure(b).size || a.localeCompare(b))) {
      const item = el("li");
      item.append(link(name, name), ` (${found.get(name)} ${found.get(name) === 1 ? "mark relies" : "marks rely"} on it)`);
      list.append(item);
    }
    panel.append(list);
    document.body.append(panel);
  }

  const needingAttention = () => Object.keys(marks).filter(n => marks[n].attention?.length);

  function attentionPanel() {
    const panel = el("div", "review-orphans");
    const close = el("button", "review-close", "close");
    close.onclick = () => panel.remove();
    panel.append(el("h3", null, "Needs your attention"), close,
      el("p", null, "Someone is waiting on you here: they asked a question, or answered yours. Mark it or reply to clear it."));
    const list = el("ul");
    for (const name of needingAttention()) {
      const item = el("li");
      item.append(link(name, name), ` (${marks[name].attention.join(", ")})`);
      list.append(item);
    }
    panel.append(list);
    document.body.append(panel);
  }

  function summarize() {
    const decls = [...document.querySelectorAll("[data-review-status]")]
      .filter(d => !d.classList.contains("review-generated"));
    const count = s => decls.filter(d => d.dataset.reviewStatus === s).length;
    const staleCount = decls.filter(d => d.dataset.reviewStale === "yes").length;
    const sources = decls.filter(d => d.dataset.reviewGap === "source").length;
    const affected = decls.filter(d => d.dataset.reviewGap === "affected").length;
    document.querySelector("#review-summary .counts").textContent =
      `✓ ${count("agree")}  ? ${count("question")}  ✗ ${count("reject")}  unmarked ${count("")}` +
      (staleCount ? `  · ${staleCount} to re-check` : "") +
      (sources + affected ? `  · ${sources} sorry, ${affected} relying on one` : "");
  }

  async function init() {
    // First, and needing no data: on a large page, the browser can be busy for seconds.
    const bar = el("div");
    bar.id = "review-summary";
    bar.append(el("span", "review-me"), el("span", "counts", "loading…"));
    // So the graph and quiz pages can link back here.
    try { sessionStorage.setItem("lean-vouch-docs", location.href); } catch {}
    const graphLink = el("a", null, "dependency graph");
    graphLink.href = "/review/diagram";
    bar.append(graphLink);
    const quizLink = el("a", null, "quiz");
    quizLink.href = "/review/quiz";
    quizLink.title = "Describe unmarked declarations from their statement alone";
    bar.append(quizLink);
    document.body.append(bar);
    for (const decl of document.querySelectorAll("main .decl")) decl.append(el("div", "review-loading", "loading review…"));
    [marks, graph] = await Promise.all([
      fetch("/review/data").then(checked),
      // A large project sends what this page needs, which for a page of no module is little;
      // a small one sends everything.
      fetch(typeof MODULE_NAME === "undefined" ? "/review/graph?marked"
        : `/review/graph?marked&module=${encodeURIComponent(MODULE_NAME)}`).then(r => r.json()),
    ]);
    graph.declarations ??= {};
    graph.library ??= {};
    for (const waiting of document.querySelectorAll(".review-loading")) waiting.remove();
    await reviewLinks.rewrite(document, a => graph.declarations[a.closest(".decl")?.id]?.lines?.[0]);
    const lost = orphans();
    if (lost.length) {
      const b = el("button", "review-orphan-button", `orphaned notes (${lost.length})`);
      b.onclick = orphanPanel;
      bar.append(b);
      // A link to page.html#review-orphans opens the list directly.
      if (location.hash === "#review-orphans") orphanPanel();
    }
    const askedButton = el("button", "review-orphan-button");
    askedButton.onclick = attentionPanel;
    const showAsked = () => {
      const asked = needingAttention().length;
      askedButton.textContent = `needs attention (${asked})`;
      askedButton.style.display = asked ? "" : "none";
    };
    showAsked();
    bar.append(askedButton);
    const changedButton = el("button", "review-orphan-button");
    changedButton.onclick = changedPanel;
    const showChanged = () => {
      const found = changedNames().size;
      changedButton.textContent = `what changed (${found})`;
      changedButton.style.display = found ? "" : "none";
    };
    showBar = () => { showAsked(); showChanged(); summarize(); };
    showChanged();
    bar.append(changedButton);
    if (location.hash === "#review-attention" && needingAttention().length) attentionPanel();
    const filters = el("details", "review-filters");
    filters.append(el("summary", null, "show plumbing"));
    for (const [group, label, title] of GROUPS) {
      const row = el("label");
      row.title = title;
      const box = el("input");
      box.type = "checkbox";
      box.checked = shownGroups.has(group);
      box.onchange = () => {
        if (box.checked) shownGroups.add(group); else shownGroups.delete(group);
        try { localStorage.setItem(storageKey, JSON.stringify([...shownGroups])); } catch {}
        reviewReload();
      };
      row.append(box, " " + label);
      filters.append(row);
    }
    bar.append(filters);
    const label = el("label");
    const toggle = el("input");
    toggle.type = "checkbox";
    toggle.checked = true;
    label.append(toggle, " hide generated");
    toggle.onchange = () => document.body.classList.toggle("review-hide-generated", toggle.checked);
    document.body.classList.add("review-hide-generated");
    bar.append(label);
    const projectEquations = [];
    const equationsLabel = el("label");
    const equationsBox = el("input");
    equationsBox.type = "checkbox";
    equationsBox.checked = openEquations;
    equationsLabel.append(equationsBox, " open equations");
    equationsBox.onchange = () => {
      openEquations = equationsBox.checked;
      try { localStorage.setItem(equationsKey, openEquations ? "1" : "0"); } catch {}
      for (const d of projectEquations) d.open = openEquations;
    };
    bar.append(equationsLabel);

    const hasGraph = !!graph.root;
    const inProject = typeof MODULE_NAME !== "undefined" &&
      (!hasGraph || (graph.roots ?? [graph.root]).some(r => MODULE_NAME === r || MODULE_NAME.startsWith(r + ".")));
    const moduleDoc = document.querySelector(".mod_doc");
    if (moduleDoc && inProject) controls(`module ${MODULE_NAME}`, moduleDoc, false);
    for (const decl of document.querySelectorAll("main .decl")) {
      if (graph.declarations[decl.id] || (inProject && !hasGraph)) {
        controls(decl.id, decl, false);
        for (const d of equations(decl)) { d.open = openEquations; projectEquations.push(d); }
      }
      else if (graph.library[decl.id]) controls(decl.id, decl, true);
    }
    summarize();
    reviewWatch(async () => {
      const fresh = await fetch("/review/data").then(checked);
      const missing = graph.complete ? [] : reviewMissing(Object.keys(fresh), fresh, d => info(d));
      if (missing.length) {
        const part = await reviewBelow(missing);
        Object.assign(graph.declarations, part.declarations);
        Object.assign(graph.library, part.library);
        closureCache.clear();
      }
      marks = fresh;
      changedNow = null;
      redraw();
    });
    // ?focus=A,B scrolls to those declarations once the review controls are in place; adding
    // &only hides the page's other declarations instead (used for screenshots).
    const params = new URLSearchParams(location.search);
    const focus = (params.get("focus") ?? "").split(",").filter(Boolean);
    if (focus.length && params.has("only")) {
      for (const d of document.querySelectorAll("main .decl, main .mod_doc"))
        if (!focus.includes(d.id)) d.style.display = "none";
      window.scrollTo(0, 0);
    } else if (focus.length) document.getElementById(focus[0])?.scrollIntoView({ block: "center" });
  }

  // doc-gen4 loads its navigation sidebar as a page in a frame; leave that page alone.
  if (window !== window.top) return;
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", init);
  else init();
})();
